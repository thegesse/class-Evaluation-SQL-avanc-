ALTER TABLE commandes RENAME TO commandes_old;

CREATE TABLE commandes (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    client_id integer NOT NULL,
    date_commande timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    montant_total numeric(12,2) NOT NULL,
    statut varchar(30) NOT NULL,
    PRIMARY KEY (id, date_commande),
    CONSTRAINT fk_commandes_client FOREIGN KEY (client_id) REFERENCES clients (id)
) PARTITION BY RANGE (date_commande);

CREATE TABLE commandes_2024 PARTITION OF commandes
    FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');

CREATE TABLE commandes_2025 PARTITION OF commandes
    FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');

CREATE TABLE commandes_2026 PARTITION OF commandes
    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

CREATE TABLE commandes_default PARTITION OF commandes DEFAULT;

INSERT INTO commandes (id, client_id, date_commande, montant_total, statut)
SELECT id, client_id, date_commande, montant_total, statut FROM commandes_old;

SELECT setval(pg_get_serial_sequence('commandes', 'id'), COALESCE(MAX(id), 1)) FROM commandes;

CREATE INDEX idx_commandes_esr
ON commandes (statut, montant_total DESC, date_commande)
INCLUDE (id, client_id);

DROP TABLE commandes_old CASCADE;
ANALYZE commandes;


EXPLAIN ANALYZE
SELECT id, client_id, date_commande, montant_total 
FROM commandes 
WHERE statut = 'LIVREE'
  AND date_commande >= '2026-01-01'
  AND date_commande < '2027-01-01'
ORDER BY montant_total DESC
LIMIT 10;

