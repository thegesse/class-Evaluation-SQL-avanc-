CREATE TABLE departements (
    dept_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_nom varchar(100) NOT NULL UNIQUE
);

-- Ajoute la colonne dept_id à la table employes existante si nécessaire
ALTER TABLE employes
    ADD COLUMN IF NOT EXISTS telephone varchar(20),
    ADD COLUMN IF NOT EXISTS dept_id integer REFERENCES departements(dept_id);

CREATE TABLE projets (
    projet_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_nom varchar(150) NOT NULL,
    chef_projet_id integer NOT NULL,
    CONSTRAINT fk_projets_chef FOREIGN KEY (chef_projet_id) REFERENCES employes(id)
);

CREATE TABLE affectations (
    employe_id integer NOT NULL,
    projet_id integer NOT NULL,
    PRIMARY KEY (employe_id, projet_id),
    CONSTRAINT fk_affectations_employe FOREIGN KEY (employe_id) REFERENCES employes(id) ON DELETE CASCADE,
    CONSTRAINT fk_affectations_projet FOREIGN KEY (projet_id) REFERENCES projets(projet_id) ON DELETE CASCADE
);

